using System.Diagnostics;
using System.Runtime.InteropServices;

namespace QuickDock.Services;

public sealed record InstalledApp(string Name, string LaunchPath, string DisplayPath);

public static class InstalledAppScanner
{
    private static readonly HashSet<string> DocumentExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".html", ".htm", ".chm", ".pdf", ".txt", ".md", ".url", ".rtf", ".png", ".jpg", ".jpeg", ".gif"
    };

    private static readonly HashSet<string> ScriptExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".cmd", ".bat", ".ps1", ".vbs", ".lua", ".wlua"
    };

    private static readonly HashSet<string> AllowedWindowsApps = new(StringComparer.OrdinalIgnoreCase)
    {
        "notepad.exe", "mspaint.exe", "snippingtool.exe", "calc.exe", "explorer.exe", "write.exe"
    };

    public static List<InstalledApp> Scan()
    {
        var found = new Dictionary<string, InstalledApp>(StringComparer.OrdinalIgnoreCase);
        object? shell = null;

        try
        {
            var shellType = Type.GetTypeFromProgID("Shell.Application");
            if (shellType is null) return [];

            var shellInstance = Activator.CreateInstance(shellType)
                                ?? throw new InvalidOperationException("无法创建 Shell.Application");
            shell = shellInstance;
            dynamic shellApp = shellInstance;
            object? folderObject = shellApp.NameSpace("shell:AppsFolder");
            if (folderObject is null) return [];
            dynamic folder = folderObject;

            dynamic items = folder.Items();
            var count = (int)items.Count;
            for (var i = 0; i < count; i++)
            {
                dynamic? item = null;
                try
                {
                    item = items.Item(i);
                    var name = ((string?)item.Name ?? string.Empty).Trim();
                    var appId = ((string?)item.Path ?? string.Empty).Trim();
                    var targetPath = ((string?)item.ExtendedProperty(
                        "System.Link.TargetParsingPath") ?? string.Empty).Trim();
                    if (string.IsNullOrWhiteSpace(name) || string.IsNullOrWhiteSpace(appId)) continue;
                    if (ShouldSkip(name, appId, targetPath)) continue;

                    var launchPath = ResolveLaunchPath(appId, targetPath);
                    if (launchPath is null) continue;

                    var key = launchPath;
                    if (!found.ContainsKey(key))
                    {
                        found[key] = new InstalledApp(
                            name,
                            launchPath,
                            targetPath.Length > 0 ? targetPath : "Windows 应用");
                    }
                }
                catch (Exception ex)
                {
                    Debug.WriteLine($"扫描应用项失败: {ex.Message}");
                }
                finally
                {
                    if (item is not null) Marshal.ReleaseComObject(item);
                }
            }

            Marshal.ReleaseComObject(items);
            Marshal.ReleaseComObject(folder);
        }
        catch (Exception ex)
        {
            Debug.WriteLine($"扫描已安装应用失败: {ex}");
        }
        finally
        {
            if (shell is not null) Marshal.ReleaseComObject(shell);
        }

        return found.Values
            .GroupBy(app => app.Name, StringComparer.CurrentCultureIgnoreCase)
            .Select(group => group
                .OrderByDescending(app => app.LaunchPath.StartsWith("shell:", StringComparison.OrdinalIgnoreCase) ? 0 : 1)
                .First())
            .OrderBy(app => app.Name, StringComparer.CurrentCulture)
            .ToList();
    }

    private static bool ShouldSkip(string name, string appId, string targetPath)
    {
        if (name.StartsWith("卸载", StringComparison.Ordinal)
            || name.Contains("卸载程序", StringComparison.Ordinal)
            || name.StartsWith("Uninstall", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        if (appId.StartsWith("http://", StringComparison.OrdinalIgnoreCase)
            || appId.StartsWith("https://", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        if (appId.StartsWith("Microsoft.AutoGenerated.", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        if (appId.StartsWith("Microsoft.Windows.", StringComparison.OrdinalIgnoreCase)
            && !appId.Contains('!'))
        {
            return true;
        }

        var extension = Path.GetExtension(targetPath.Length > 0 ? targetPath : appId);
        if (!string.IsNullOrEmpty(extension) && DocumentExtensions.Contains(extension))
        {
            return true;
        }

        if (!string.IsNullOrEmpty(extension) && ScriptExtensions.Contains(extension))
        {
            return true;
        }

        if (extension.Equals(".msc", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        if (targetPath.Length == 0)
        {
            return appId.StartsWith('{')
                   && appId.IndexOf(".exe", StringComparison.OrdinalIgnoreCase) < 0;
        }

        var windowsDirectory = Environment.GetFolderPath(Environment.SpecialFolder.Windows)
            .TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar;
        if (targetPath.StartsWith(windowsDirectory, StringComparison.OrdinalIgnoreCase))
        {
            var executable = Path.GetFileName(targetPath);
            return !AllowedWindowsApps.Contains(executable);
        }

        return false;
    }

    private static string? ResolveLaunchPath(string appId, string targetPath)
    {
        if (targetPath.Length > 0 && File.Exists(targetPath))
        {
            return targetPath;
        }

        var isDrivePath = appId.Length >= 2 && appId[1] == ':';
        var isUncPath = appId.StartsWith(@"\\", StringComparison.Ordinal);
        if (isDrivePath || isUncPath)
        {
            return File.Exists(appId) ? appId : null;
        }

        return "shell:AppsFolder\\" + appId;
    }
}
